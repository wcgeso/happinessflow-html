with open('src/constants/cards.ts', 'r', encoding='utf-8') as f:
    lines = f.readlines()

new_lines = []
for line in lines:
    match = re.search(r"id:\s*'([A-Z0-9]+)'", line)
    if match:
        card_id = match.group(1)
        if card_id in updates:
            # Replace description carefully
            # Usually looks like: description: '...',
            # We want to replace whatever is inside description: '...'
            # Because it might contain escaped quotes, it's a bit tricky, but since we know it's a single line string mostly:
            new_line = re.sub(r"description:\s*'(.*?)'(?=,)", f"description: '{updates[card_id]}'", line)
            new_lines.append(new_line)
            continue
    new_lines.append(line)

with open('src/constants/cards.ts', 'w', encoding='utf-8') as f:
    f.writelines(new_lines)

