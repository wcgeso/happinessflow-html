with open('src/constants/cards.ts', 'r', encoding='utf-8') as f:
    content = f.read()

for cid, text in updates.items():
    # Use backticks so literal newlines are valid
    # Replace literal \n in string with real newlines, because the string above has \\n
    # When written as f"`{real_text}`", we need to convert \n to real newline
    real_text = text.replace('\\n', '\n')
    
    # We find the object block for this ID
    # This regex is robust: finds id: 'CID' and then matches up to description: '...' or description: `...`
    # and replaces the whole description value.
    # Note: re.sub with a replacement string treats \ as escape, so we pass a lambda
    
    def replacer(match):
        prefix = match.group(1)
        suffix = match.group(3)
        return f"{prefix}description: `{real_text}`{suffix}"
    
    # pattern: group 1 is the part from id: 'CID' up to just before description:
    # group 2 is the current description string (either '' or ``)
    # group 3 is the rest
    # We'll use a regex that matches from { id: 'CID' to description: ...
    pattern = r"(\{ id: '" + cid + r"'.*?)(description:\s*(?:'[^']*'|`[^`]*`))(.*?\})"
    content = re.sub(pattern, replacer, content, flags=re.DOTALL)

    if cid == 'H021':
        content = re.sub(r"(\{ id: 'H021'.*?cashCost:\s*)6000( *\})", r"\g<1>15200\g<2>", content, flags=re.DOTALL)

with open('src/constants/cards.ts', 'w', encoding='utf-8') as f:
    f.write(content)

